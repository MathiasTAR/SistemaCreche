    CIFON BOOLEAN,
    ENERGIA_ELETRICA BOOLEAN,
    AGUA_ENCANADA BOOLEAN,
    COLETOR_PUBLICO BOOLEAN
);

CREATE TABLE COMPOSICAO_FAMILIAR (
    ID_COMPOSICAO_FAMILIAR INT AUTO_INCREMENT PRIMARY KEY,
    ID_CRIANCA INT NOT NULL,
    RENDA_FAMILIAR_TOTAL DECIMAL(10,2) NOT NULL,
    RENDA_PER_CAPITA DECIMAL(10,2) NOT NULL,
    TOTAL_MEMBROS INT,
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA)
);

# =======================
# 📄 MATRÍCULAS
# =======================

CREATE TABLE PRE_MATRICULA (
    ID_PRE_MATRICULA INT AUTO_INCREMENT PRIMARY KEY,
    ID_CRIANCA INT NOT NULL,
    SERIE_TEMP VARCHAR(50),
	ANO_LETIVO_TEMP INT,
    DATA_PREMATRICULA DATE NOT NULL,
    SITUACAO_HABITACIONAL INT,
    SITUACAO_PREMATRICULA ENUM('APROVADA','EM_ANALISE','CANCELADA','REPROVADA') DEFAULT 'EM_ANALISE',
    OBSERVACAO TEXT,
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA),
    FOREIGN KEY (SITUACAO_HABITACIONAL) REFERENCES SITUACAO_HABITACIONAL(ID_SITUACAO_HAB)
);

CREATE TABLE MATRICULA (
    ID_MATRICULA INT AUTO_INCREMENT PRIMARY KEY,
    ID_CRIANCA INT NOT NULL,
    ID_PRE_MATRICULA INT,
    DATA_MATRICULA DATE,
    SERIE ENUM('BERCARIO_I', 'BERCARIO_II', 'MATERNAL_I', 'MATERNAL_II', 'PRE_I', 'PRE_II'),
    ANO_LETIVO YEAR NOT NULL,
    ORIENT_RECEBIDA BOOLEAN,
    DATA_DESLIGAMENTO DATE,
    SITUACAO_MAT ENUM('ATIVA','CONCLUIDA','CANCELADA', 'VENCIDA') DEFAULT 'ATIVA',
    DATA_VENCIMENTO DATE NOT NULL,
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA),
    FOREIGN KEY (ID_PRE_MATRICULA) REFERENCES PRE_MATRICULA(ID_PRE_MATRICULA)
);

CREATE TABLE BENS_FAMILIA (
    ID_BENS_FAMILIA BIGINT AUTO_INCREMENT PRIMARY KEY,
    ID_COMPOSICAO_FAMILIAR INT NOT NULL,
    ID_TIPO_BEM INT NOT NULL,
    POSSUI BOOLEAN NOT NULL DEFAULT TRUE,
    QUANTIDADE INT DEFAULT 1,
    FOREIGN KEY (ID_COMPOSICAO_FAMILIAR) REFERENCES COMPOSICAO_FAMILIAR(ID_COMPOSICAO_FAMILIAR),
    FOREIGN KEY (ID_TIPO_BEM) REFERENCES TIPO_BEM(ID_TIPO_BEM)
);


# =======================
# 🧾 HISTÓRICO DE MATRÍCULA (somente sistema)
# =======================

CREATE TABLE HISTORICO_MATRICULA (
    ID_HIST_MATRI INT AUTO_INCREMENT PRIMARY KEY,
    ID_MATRICULA INT NOT NULL,
    ID_CRIANCA INT NOT NULL,
    DATA_REGISTRO DATETIME DEFAULT CURRENT_TIMESTAMP,
    ACAO ENUM('CRIACAO','RENOVACAO','CANCELAMENTO','CONCLUSAO','ALTERACAO') NOT NULL,
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA),
    FOREIGN KEY (ID_MATRICULA) REFERENCES MATRICULA(ID_MATRICULA)
);


