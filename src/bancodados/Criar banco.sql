CREATE TABLE SITUACAO_HABITACIONAL (
    ID_SITUACAO_HAB INT AUTO_INCREMENT PRIMARY KEY,
    CASA_PROPRIA BOOLEAN,
    CASA_CEDIDA BOOLEAN,
    CASA_ALUGADA BOOLEAN,
    VALOR_ALUGUEL DECIMAL(10,2),
    NUMERO_COMODOS INT,
    TIPO_PISO ENUM('CIMENTO','LAJOTA','CHAO_BATIDO','CERAMICA','MADEIRA','OUTRO'),
    TIPO_MORADIA ENUM('TIJOLO','TAIPA','MADEIRA','MISTA','ALVENARIA','OUTRO'),
