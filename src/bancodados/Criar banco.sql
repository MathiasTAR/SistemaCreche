DROP DATABASE IF EXISTS CRECHE;
CREATE DATABASE CRECHE;
USE CRECHE;

# =======================
# 📘 TABELAS BASE
# =======================

CREATE TABLE PESSOA (
    ID_PESSOA INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    CPF CHAR(11) UNIQUE NOT NULL,
    RG VARCHAR(20) UNIQUE NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    OUTRO_CONTATO VARCHAR(20)
);

CREATE TABLE ENDERECO (
    ID_ENDERECO BIGINT AUTO_INCREMENT PRIMARY KEY,
    LOGRADOURO VARCHAR(255) NOT NULL,
    NUMERO VARCHAR(20) NOT NULL,
    COMPLEMENTO VARCHAR(100),
    BAIRRO VARCHAR(100) NOT NULL,
    MUNICIPIO VARCHAR(100) NOT NULL,
    CEP VARCHAR(10) NOT NULL,
    UF CHAR(2) NOT NULL,
    PONTO_REFERENCIA VARCHAR(100),
    TELEFONE_RESIDENCIAL VARCHAR(20),
    UNIQUE(LOGRADOURO, NUMERO, BAIRRO, MUNICIPIO, UF, CEP)
);

CREATE TABLE TIPO_AUXILIO (
    ID_TIPO_AUXILIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_AUXILIO VARCHAR(255) UNIQUE
);

CREATE TABLE CLASSIFICACAO_ESPECIAL (
    ID_CLASSIFICACAO_ESPECIAL INT AUTO_INCREMENT PRIMARY KEY,
    CLASSIFICACAO_ESPECIAL VARCHAR(255),
    CODIGO VARCHAR(255),
    DESCRICAO TEXT,
    STATUS_CLASSIFICACAO_ESPECIAL BOOLEAN NOT NULL
);

CREATE TABLE ALERGIA (
    ID_ALERGIA INT AUTO_INCREMENT PRIMARY KEY,
    NOME_ALERGIA VARCHAR(100)
);

CREATE TABLE TIPO_RESPONSAVEL (
    ID_TIPO_RESPONSAVEL INT AUTO_INCREMENT PRIMARY KEY,
    TIPO_RESPONSAVEL VARCHAR(255)
);

CREATE TABLE RESPONSAVEL (
    ID_RESPONSAVEL INT AUTO_INCREMENT PRIMARY KEY,
    ID_TIPO_RESPONSAVEL INT,
    ID_PESSOA INT NOT NULL,
    TELEFONE VARCHAR(20) NOT NULL,
    LOCAL_TRABALHO VARCHAR(100),
    AUXILIO_GOV BOOLEAN NOT NULL,
    ID_TIPO_AUXILIO INT,
    NUMERO_NIS VARCHAR(255),
    FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA),
    FOREIGN KEY (ID_TIPO_AUXILIO) REFERENCES TIPO_AUXILIO(ID_TIPO_AUXILIO),
    FOREIGN KEY (ID_TIPO_RESPONSAVEL) REFERENCES TIPO_RESPONSAVEL(ID_TIPO_RESPONSAVEL)
);

CREATE TABLE CRIANCA (
    ID_CRIANCA INT AUTO_INCREMENT PRIMARY KEY,
    FOTO VARCHAR(255),
    NOME VARCHAR(255),
	CPF CHAR(11) UNIQUE NOT NULL,
    RG VARCHAR(20) UNIQUE NOT NULL,
    DATA_NASCIMENTO DATE NOT NULL,
    SEXO ENUM('MASCULINO','FEMININO','OUTRO') NOT NULL,
    COR_RACA ENUM('BRANCA','PRETA','PARDA','AMARELA','INDIGENA', 'OUTRO'),
    POSSUI_IRMAO_CRECHE BOOLEAN DEFAULT False,
    POSSUI_IRMAO_GEMEO BOOLEAN DEFAULT False,
    CARTSUS CHAR(15) UNIQUE NOT NULL,
    UNIDADE_SAUDE VARCHAR(100),
    MUNICIPIO_NASCIMENTO VARCHAR(255),
    MUNICIPIORESGISTRO VARCHAR(255),
    CARTORIO_REGISTRO VARCHAR(255),
    CERTIDAO_NASCIMENTO_NUM VARCHAR(255),
    DATA_EMISSAO_CERTIDAO DATE,
    ORG_EMISSOR_CERTIDAO VARCHAR(10),
    RESTRICAO_ALIMENTAR BOOLEAN NOT NULL,
    DESCRICAO_RESTRICOES_ALIMENTARES VARCHAR(255),
    ALERGIA BOOLEAN NOT NULL,
    PROBLEMA_SAUDE TEXT,
    RESTRI_ALIMENTAR TEXT,
    MOB_RED ENUM('TEMPORARIA','PERMANENTE','NENHUMA'),
    DEF_MULTI BOOLEAN NOT NULL,
    EDUC_ESPECIAL BOOLEAN NOT NULL,
    RESPONSAVEL_BENEFICIARIO_AUXILIO_GOV BOOLEAN NOT NULL,
    ID_RESPONSAVEL INT,
    ID_TIPO_AUXILIO INT,
    ID_CLASSIFICACAO_ESPECIAL INT,
    STATUS_CLASSIFICACAO_ESPECIAL BOOLEAN NOT NULL DEFAULT FALSE,
    ID_PAI INT,
    ID_MAE INT,
    ID_IRMAO_GEMEO INT,
    FOREIGN KEY (ID_TIPO_AUXILIO) REFERENCES TIPO_AUXILIO(ID_TIPO_AUXILIO),
    FOREIGN KEY (ID_RESPONSAVEL) REFERENCES RESPONSAVEL(ID_RESPONSAVEL),
    FOREIGN KEY (ID_CLASSIFICACAO_ESPECIAL) REFERENCES CLASSIFICACAO_ESPECIAL(ID_CLASSIFICACAO_ESPECIAL),
    FOREIGN KEY (ID_PAI) REFERENCES PESSOA(ID_PESSOA),
    FOREIGN KEY (ID_MAE) REFERENCES PESSOA(ID_PESSOA),
    FOREIGN KEY (ID_IRMAO_GEMEO) REFERENCES CRIANCA(ID_CRIANCA)
);

CREATE TABLE CRIANCA_ALERGIA (
    ID_CRIANCA_ALERGIA INT AUTO_INCREMENT PRIMARY KEY,
    ID_CRIANCA INT NOT NULL,
    ID_ALERGIA INT NOT NULL,
    FOREIGN KEY (ID_ALERGIA) REFERENCES ALERGIA(ID_ALERGIA),
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA)
);

CREATE TABLE MEMBRO_FAMILIA (
    ID_MEMBRO_FAMILIA BIGINT AUTO_INCREMENT PRIMARY KEY,
    ID_CRIANCA INT NOT NULL,
    NOME VARCHAR(150) NOT NULL,
    IDADE INT NOT NULL,
    PARENTESCO ENUM('MAE','PAI','IRMAO','IRMA','AVO','TIO','TIA','RESPONSAVEL_LEGAL','OUTRO'),
    SITUACAO_ESCOLAR ENUM(
        'CRECHE','PRE_ESCOLA','ENSINO_FUNDAMENTAL_1_1_5_ANO',
        'ENSINO_FUNDAMENTAL_2_6_9_ANO','ENSINO_FUNDAMENTAL_INCOMPLETO',
        'ENSINO_FUNDAMENTAL_COMPLETO','ENSINO_MEDIO_INCOMPLETO',
        'ENSINO_MEDIO_COMPLETO','ENSINO_TECNICO_INTEGRADO_MEDIO',
        'ENSINO_MEDIO_PROFISSIONALIZANTE','ENSINO_SUPERIOR_INCOMPLETO',
        'ENSINO_SUPERIOR_COMPLETO','POS_GRADUACAO_LATO_SENSU_ESPECIALIZACAO',
        'MESTRADO','DOUTORADO','POS_DOUTORADO','EJA_FUNDAMENTAL',
        'EJA_MEDIO','ALFABETIZACAO_DE_ADULTOS','ANALFABETO','NAO_INFORMADO'
    ),
    SITUACAO_EMPREGO ENUM(
        'EMPREGADO_FORMAL','EMPREGADO_INFORMAL','SERVIDOR_PUBLICO','AUTONOMO',
        'EMPREGADOR','APOSENTADO','PENSIONISTA','DESEMPREGADO','DO_LAR',
        'ESTUDANTE','BOLSISTA','INCAPAZ_TRABALHAR','OUTRO'
    ),
    RENDA DECIMAL(10,2) NOT NULL,
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA)
);

CREATE TABLE PESSOA_AUTORIZADA (
    ID_PESSOA_AUT INT AUTO_INCREMENT PRIMARY KEY,
    ID_PESSOA INT,
    ID_CRIANCA INT,
    PARENTESCO ENUM(
        'MAE','PAI','IRMAO','IRMA','AVO','TIO','TIA',
        'RESPONSAVEL_LEGAL','PRIMO','PRIMA','NENHUM'
    ),
    TELEFONE VARCHAR(50),
    FOREIGN KEY (ID_PESSOA) REFERENCES PESSOA(ID_PESSOA),
    FOREIGN KEY (ID_CRIANCA) REFERENCES CRIANCA(ID_CRIANCA)
);

